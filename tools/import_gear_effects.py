"""Regenerate the small offline lookup used with live Gearwise tooltips."""
import json
import re
from collections import defaultdict
from pathlib import Path
from urllib.request import urlopen


REV = "a8bd7fd83a3a7c5102012ed87d86a71d175b3a89"
BASE = f"https://raw.githubusercontent.com/wowsims/forever/{REV}/"
OUT = Path(__file__).resolve().parents[1] / "src/Modules/Gearwise/EffectData.lua"


def fetch(path):
    with urlopen(BASE + path, timeout=30) as response:
        return response.read().decode()


def main():
    db = json.loads(fetch("assets/database/db.json"))
    set_pieces = defaultdict(list)
    lines = ["-- Numerical reference data from WoWSims Forever " + REV,
             "-- https://github.com/wowsims/forever. Generated by tools/import_gear_effects.py.",
             "--[[\n" + fetch("LICENSE").strip() + "\n]]",
             "local _, ns = ...", "ns.weaponProcRates = {"]
    for item in sorted(db["items"], key=lambda row: row["id"]):
        if item.get("setId"):
            set_pieces[item["setId"]].append(item["id"])
        rate = item.get("procRate", {})
        effects = item.get("itemEffects", [])
        if (item.get("type") not in (13, 14) or len(effects) != 1
                or rate.get("status") not in (1, 2, 3) or rate.get("kind") not in (1, 2)
                or not rate.get("rate") or effects[0].get("maxCumulativeStacks", 0) > 1):
            continue
        unit = "PPM" if rate["kind"] == 1 else "%"
        source = {1: "measured", 2: "client data", 3: "observed"}[rate["status"]]
        cooldown = effects[0].get("proc", {}).get("icdMs", 0) / 1000
        lines.append(f'    [{item["id"]}] = {{{rate["rate"]}, "{unit}", "{source}", {cooldown:g}}},')
    lines.extend(["}", "ns.setMembers = {"])
    for set_id, members in sorted(set_pieces.items()):
        lines.append(f"    [{set_id}] = {{" + ", ".join(map(str, members)) + "},")
    # The client sometimes hides the threshold on an already active bonus.
    # Store complete ordered thresholds, including the sim's unmodeled rows.
    source = fetch("sim/common/forever/item_sets_auto_gen.go")
    thresholds = {}
    for set_id, body in re.findall(r"shared\.NewParsedItemSet\((\d+),[^\n]+\{\n(.*?)\n\s*\}\)", source, re.S):
        tiers = re.findall(r"^\s*(?://\s*)?(\d+):\s*\{[\d, ]+\},", body, re.M)
        if tiers:
            thresholds[int(set_id)] = tiers
    manual = fetch("sim/common/forever/items_sets.go")
    for block in re.findall(r"core\.NewItemSet\(core\.ItemSet\{(.*?)\n\}\)", manual, re.S):
        set_id = re.search(r"^\s*ID:\s*(\d+),", block)
        bonuses = re.search(r"Bonuses:\s*map\[int32\]core\.ApplySetBonus\{(.*?)\n\t\},", block, re.S)
        if set_id and bonuses:
            tiers = re.findall(r"^\t\t(\d+):", bonuses[1], re.M)
            if tiers:
                thresholds[int(set_id[1])] = sorted(tiers, key=int)
    lines.extend(["}", "ns.setThresholds = {"])
    for set_id, tiers in sorted(thresholds.items()):
        lines.append(f"    [{set_id}] = {{" + ", ".join(tiers) + "},")
    OUT.write_text("\n".join(lines + ["}", ""]), encoding="utf-8")


if __name__ == "__main__":
    main()
